export const STANDARD_EVENT_NAMES: string[] = Object.keys(EVENT_TYPE_LABELS)
const eventTypesWithDataTypes = (dataTypes: DataType[]): EventType[] =>
  (Object.keys(EVENT_DATA_TYPES) as EventType[]).filter((eventType) => dataTypes.includes(EVENT_DATA_TYPES[eventType]))

export const PLAN_ID_EVENT_TYPES: EventType[] = eventTypesWithDataTypes(['plan_enrollment', 'custom'])
export const CONTENTS_EVENT_TYPES: EventType[] = eventTypesWithDataTypes(['contents', 'plan_enrollment', 'custom'])

export const EVENT_TYPE_IS_CUSTOM: DependsOnConditions = {
  match: 'all',
  conditions: [{ fieldKey: 'event_type', operator: 'is', value: 'custom' }]
}

export const ACTION_SOURCE_IS_WEB: DependsOnConditions = {
  match: 'all',
  conditions: [{ fieldKey: 'action_source', operator: 'is', value: 'web' }]
}

export const AMOUNT_IS_PRESENT: DependsOnConditions = {
  match: 'all',
  conditions: [{ fieldKey: 'amount', operator: 'is_not', value: undefined }]
}

export const EVENT_TYPE_SUPPORTS_PLAN_ID: DependsOnConditions = {
  match: 'any',
  conditions: PLAN_ID_EVENT_TYPES.map((eventType) => ({ fieldKey: 'event_type', operator: 'is', value: eventType }))
}

export const EVENT_TYPE_SUPPORTS_CONTENTS: DependsOnConditions = {
  match: 'any',
  conditions: CONTENTS_EVENT_TYPES.map((eventType) => ({ fieldKey: 'event_type', operator: 'is', value: eventType }))
}

